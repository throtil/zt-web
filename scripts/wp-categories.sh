#!/usr/bin/env bash
# Статьи, у которых рубрика не одна.
#
#   ./scripts/wp-categories.sh
#
# Правило проекта: статья лежит ровно в одной рубрике. Рубрика говорит, что за
# предмет описан, а не в каких списках статью хотелось бы увидеть; несколько
# рубрик у одной статьи превращают тематический список в смесь форматов.
#
# Заслона нет. Ядро ставит рубрики отдельно от самой записи, и обрезать выбор
# при сохранении значило бы молча выбросить то, что редактор выбрал: он увидит
# результат не сразу и не поймёт, что произошло. Прятать чекбоксы — переписывать
# панель редактора блоков на JavaScript, то есть держать полсотни строк, зависящих
# от внутренностей ядра. Для зонда это дороже пользы.
#
# Поэтому здесь правило и проверка задним числом. Нарушение видно сразу и
# чинится в админке двумя щелчками — тем и отличается от разъехавшегося словаря
# меток, который незаметен и склеивается вручную.
#
# Заодно показываются статьи в рубрике по умолчанию (`uncategorized`): её нет в
# дереве, и попавшая туда статья не видна ни в одном разделе сайта.
#
# Обоснование правила — openspec/changes/product-structure-poc/specs/content-taxonomy.

set -euo pipefail

. "$(dirname -- "${BASH_SOURCE[0]}")/lib/common.sh"

zt_load_env
zt_require_stack_running

# Выравнивание по символам, а не по байтам: printf в PHP считает байты, и
# кириллические колонки разъезжаются вдвое. Та же причина, что в wp-templates.sh.
zt_wp eval '
	$pad = static function ( $text, $width ) {
		return $text . str_repeat( " ", max( 1, $width - mb_strlen( $text ) ) );
	};

	// Статусы перечислены поимённо, а не словом «any»: черновики — защищённый
	// статус, и запрос со словом «any» отдаёт их только тому, кто вправе их
	// читать, а под wp-cli пользователя нет. Незаконченный обзор с двумя
	// рубриками — как раз тот случай, который важно поймать до публикации.
	$posts = get_posts(
		array(
			"post_type"        => "post",
			"post_status"      => array( "publish", "future", "draft", "pending", "private" ),
			"numberposts"      => -1,
			"suppress_filters" => false,
		)
	);

	if ( ! $posts ) {
		echo "статей ещё нет\n";
		exit;
	}

	$bad = array();
	foreach ( $posts as $post ) {
		$names = wp_get_post_categories( $post->ID, array( "fields" => "all" ) );
		$slugs = wp_list_pluck( $names, "slug" );

		if ( 1 === count( $slugs ) && "uncategorized" !== $slugs[0] ) {
			continue;
		}

		$bad[] = array(
			$post->ID,
			$post->post_title,
			$slugs ? implode( ", ", wp_list_pluck( $names, "name" ) ) : "рубрики нет",
		);
	}

	printf( "статей: %d, из них с одной рубрикой: %d\n", count( $posts ), count( $posts ) - count( $bad ) );

	if ( ! $bad ) {
		echo "правило «одна статья — одна рубрика» соблюдается\n";
		exit;
	}

	echo "\n", $pad( "id", 6 ), $pad( "статья", 40 ), "рубрики\n";
	foreach ( $bad as $row ) {
		echo $pad( (string) $row[0], 6 ), $pad( mb_strimwidth( $row[1], 0, 38, "…" ), 40 ), $row[2], "\n";
	}

	echo "\nПравило: статья лежит ровно в одной рубрике, и это не рубрика по умолчанию.\n";
	echo "Чинится в админке: у статьи снять лишние отметки рубрик.\n";
'
