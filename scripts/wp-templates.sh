#!/usr/bin/env bash
# Откуда берётся каждый шаблон страницы: из файла репозитория или из базы.
#
#   ./scripts/wp-templates.sh              показать список
#   ./scripts/wp-templates.sh reset <слог> отменить правку шаблона в базе
#
# Части шаблонов — шапка и подвал — показываются здесь же. Они отдельный тип
# записи, и по невнимательности их легко упустить: перебитая шапка не попала бы
# в список, составленный по одним шаблонам страниц. Для шапки это особенно
# некстати — в ней меню, то есть место, куда редактор ходит по делу.
#
# Зачем это нужно. Запись шаблона в базе заменяет одноимённый файл темы
# целиком, и правка файла после этого не видна на сайте. Ошибки при этом нет
# нигде: деплой проходит, журнал чист, страница просто не меняется. Первое, что
# стоит проверить в таком случае, — не перебит ли шаблон записью в базе.
#
# То же видно в админке: «Внешний вид → Редактор → Шаблоны», у перебитых есть
# действие «Очистить изменения». Скрипт нужен затем, что в админку за этим
# лезть не всегда удобно, а вопрос возникает во время разбора деплоя.
#
# Правило проекта: шаблоны меняются только коммитом, в том числе
# разработчиком. Подробности и обоснование — в docs/theme-layers.md.

set -euo pipefail

. "$(dirname -- "${BASH_SOURCE[0]}")/lib/common.sh"

zt_load_env
zt_require_stack_running

case "${1:-list}" in
	list)
		# Выравнивание считается по символам, а не по байтам: printf в PHP
		# считает байты, и в кириллической колонке столбцы разъезжаются вдвое.
		zt_wp eval '
			$pad = static function ( $text, $width ) {
				return $text . str_repeat( " ", max( 1, $width - mb_strlen( $text ) ) );
			};

			$rows = array(
				"шаблон" => get_block_templates(),
				"часть"  => get_block_templates( array(), "wp_template_part" ),
			);

			if ( ! array_filter( $rows ) ) {
				echo "шаблонов не найдено\n";
				exit;
			}

			$custom = 0;
			echo $pad( "что", 10 ), $pad( "слог", 20 ), $pad( "откуда", 24 ), "файл в теме\n";
			foreach ( $rows as $kind => $templates ) {
				foreach ( $templates as $t ) {
					$is_custom = ( "custom" === $t->source );
					$custom   += $is_custom ? 1 : 0;
					echo $pad( $kind, 10 ),
						$pad( $t->slug, 20 ),
						$pad( $is_custom ? "из базы (файл перебит)" : "из файла", 24 ),
						( $t->has_theme_file ? "есть" : "нет" ), "\n";
				}
			}

			echo "\n";
			if ( $custom > 0 ) {
				printf( "перебито записями в базе: %d — правка файлов этих шаблонов не видна\n", $custom );
			} else {
				echo "все шаблоны берутся из файлов репозитория\n";
			}
		'
		;;
	reset)
		slug="${2:-}"
		[ -n "$slug" ] || zt_die "не указан слог шаблона: ./scripts/wp-templates.sh reset page"

		# Слог не подставляется в исходный текст PHP, а передаётся аргументом
		# команды. Причина не в стиле: в двойных кавычках PHP считает частью
		# имени переменной любые байты со старшим битом, поэтому «$slug» с
		# кавычками-ёлочками разбирается как переменная с именем `slug»`, и
		# сообщение печатается с пустым слогом. Поймано на этом же скрипте.
		post_id="$(zt_wp post list --post_type=wp_template,wp_template_part --post_status=any \
			--name="$slug" --field=ID --format=ids 2>/dev/null | tr -d '\r')"

		if [ -z "$post_id" ]; then
			zt_log "шаблон «$slug» в базе не перебит, отменять нечего"
			exit 0
		fi

		# Одним слогом могут называться шаблон и часть шаблона — тогда список
		# вернёт два идентификатора, и удалять вслепую нельзя.
		case "$post_id" in
			*[![:digit:]]*)
				zt_die "слогу «$slug» соответствует несколько записей ($post_id); отменить можно в админке"
				;;
		esac

		# Удаляется запись, а не файл: после удаления хозяином снова становится
		# файл темы. Это то же самое, что «Очистить изменения» в админке.
		zt_wp post delete "$post_id" --force >/dev/null
		zt_log "правка шаблона «$slug» отменена, хозяином снова стал файл"
		;;
	*)
		zt_die "неизвестный аргумент «$1»; ожидается list или reset <слог>"
		;;
esac
